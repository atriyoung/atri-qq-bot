    def pre_message_update(self, user_message: str) -> tuple[EmotionSnapshot, RelationshipSnapshot]:
        """消息处理前的状态快照"""
        return self.emotion.get_current(), self.relationship.get_current()

    def post_message_update(self, user_message: str) -> tuple[EmotionSnapshot, RelationshipSnapshot]:
        """消息处理后更新情绪和好感度"""
        trigger = self.emotion.analyze_trigger(user_message)
        self.emotion.update(trigger)

        _, delta = self.relationship.analyze_affection_delta(user_message)
        self.relationship.update(delta)

